// Generates src/data/teamDirectory.js from the main app's roster
// (../../fanlog/teams.js) so the embedded demo knows every team the landing app
// can send it. Run: node scripts/gen-team-directory.mjs
//
// Preserves the original 50 teams' hand-authored shortNames; derives nicknames
// for the rest by stripping the city prefix, with explicit overrides where that
// doesn't yield a clean name (mostly MLS "… FC/SC" and a couple CFL).
import { writeFileSync } from 'node:fs';
import { sportsData } from '../../fanlog/teams.js';
import { TEAM_DIRECTORY as EXISTING } from '../src/data/teamDirectory.js';

const SPORT = { nfl: 'Football', nba: 'Basketball', nhl: 'Hockey', mlb: 'Baseball', mls: 'Soccer', cfl: 'Football' };

const SHORT_OVERRIDES = {
  // New MLS (city-strip leaves "FC"/"SC" or reads awkwardly)
  austin: 'Austin FC', cf_montreal: 'CF Montréal', charlotte_fc: 'Charlotte FC', fire: 'Chicago Fire',
  rapids: 'Rapids', dc_united: 'D.C. United', fc_dallas: 'FC Dallas', dynamo: 'Dynamo',
  minnesota_utd: 'Minnesota Utd', nashville_sc: 'Nashville SC', revolution: 'Revolution',
  orlando_city: 'Orlando City', philadelphia_union: 'Union', rsl: 'Real Salt Lake',
  red_bulls: 'Red Bulls', san_diego_fc: 'San Diego FC', earthquakes: 'Earthquakes',
  sporting_kc: 'Sporting KC', stlouis_city: 'St. Louis City', vancouver_wc: 'Whitecaps',
  // CFL edge cases (name doesn't start with city)
  bclions: 'Lions', roughriders: 'Roughriders'
};

function nickname(id, name, city) {
  if (EXISTING[id]) return EXISTING[id].shortName; // keep the original 50 exactly
  if (SHORT_OVERRIDES[id]) return SHORT_OVERRIDES[id];
  if (city && name.startsWith(city + ' ')) return name.slice(city.length).trim();
  return name;
}

const lines = [];
let count = 0;
for (const lg of Object.keys(sportsData)) {
  const L = lg.toUpperCase();
  lines.push(`\n  // ${L}`);
  for (const t of sportsData[lg].teams) {
    const sn = nickname(t.id, t.name, t.city);
    lines.push(
      `  ${t.id}: { id: ${JSON.stringify(t.id)}, name: ${JSON.stringify(t.name)}, shortName: ${JSON.stringify(sn)}, league: ${JSON.stringify(L)}, sport: ${JSON.stringify(SPORT[lg])}, logo: ${JSON.stringify(t.logo)}, color: ${JSON.stringify(t.primary)}, accentColor: ${JSON.stringify(t.secondary)} },`
    );
    count++;
  }
}

const out =
  `// AUTO-GENERATED by scripts/gen-team-directory.mjs from ../../fanlog/teams.js.\n` +
  `// Mirrors the main app roster so the embedded demo recognizes every team.\n` +
  `export const TEAM_DIRECTORY = {${lines.join('\n')}\n};\n`;

writeFileSync(new URL('../src/data/teamDirectory.js', import.meta.url), out);
console.log(`teamDirectory.js written — ${count} teams`);
