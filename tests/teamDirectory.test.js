import { describe, expect, it } from 'vitest';
import { TEAM_DIRECTORY } from '../src/data/teamDirectory.js';

const teams = Object.entries(TEAM_DIRECTORY);

describe('TEAM_DIRECTORY (generated by scripts/gen-team-directory.mjs)', () => {
  it('is keyed by each team id', () => {
    for (const [key, t] of teams) expect(t.id).toBe(key);
  });

  it('covers every league the landing page offers', () => {
    const leagues = new Set(teams.map(([, t]) => t.league));
    expect([...leagues].sort()).toEqual(['BUNDESLIGA', 'CFL', 'EPL', 'LALIGA', 'LIGUE1', 'MLB', 'MLS', 'NBA', 'NFL', 'NHL', 'SERIEA']);
  });

  it('every team is fully described', () => {
    for (const [id, t] of teams) {
      expect(t.name, id).toBeTruthy();
      expect(t.shortName, id).toBeTruthy();
      expect(t.shortName.length, id).toBeLessThanOrEqual(t.name.length);
      expect(['Football', 'Basketball', 'Hockey', 'Baseball', 'Soccer'], id).toContain(t.sport);
      expect(t.color, id).toMatch(/^#[0-9A-Fa-f]{6}$/);
      expect(t.accentColor, id).toMatch(/^#[0-9A-Fa-f]{6}$/);
      expect(t.logo, id).toMatch(/^(https:\/\/|\/logos\/)/);
    }
  });

  it('team names are unique', () => {
    const names = teams.map(([, t]) => t.name);
    expect(new Set(names).size).toBe(names.length);
  });
});
